import torch
import torch.nn as nn

from models.virchow2 import Virchow2Encoder

from Experiments.ex1_notopk.fusion_ex1_notopk import (
    CrossAttentionFusionEx1NoTopK
)

from modules.ordinal_head import OrdinalRegressionHead


class HER2FormerEx1NoTopK(nn.Module):
    """
    HER2Former - Experiment 1: No Top-K Token Routing

    Ablation experiment:
        Removes the Top-K Token Routing module.

    Architecture
    ------------

        Input Image
             |
             v
        Virchow2 Encoder
             |
        -------------------------
        |                       |
        CLS Token           All Patch Tokens
        [B,1280]            [B,256,1280]
                                |
                                v
                    Cross Attention Fusion
                                |
                                v
                     HER2 Representation
                           [B,1280]
                                |
                                v
                     Ordinal Regression Head
                                |
                                v
                       Ordinal Logits
                            [B,3]


    Difference from the main HER2Former
    ------------------------------------

    Main model:
        Virchow2
            -> Top-K Token Routing
            -> Cross Attention
            -> Ordinal Head

    Experiment 1:
        Virchow2
            -> ALL Patch Tokens
            -> Cross Attention
            -> Ordinal Head


    Purpose
    -------

    This experiment evaluates whether the proposed
    Top-K Token Routing mechanism contributes to
    HER2 grading performance.

    All other major components are kept unchanged
    as much as possible.
    """

    def __init__(
        self,
        freeze_backbone=False,
        embed_dim=1280,
        num_heads=8,
        num_classes=4,
        dropout=0.1,
    ):
        super().__init__()

        # ==================================================
        # Backbone
        # ==================================================

        self.encoder = Virchow2Encoder(
            freeze_backbone=freeze_backbone
        )

        # ==================================================
        # Cross Attention Fusion
        # ==================================================
        #
        # IMPORTANT:
        # No Top-K selector is used in this experiment.
        #
        # All 256 patch tokens generated by Virchow2
        # are passed directly to the fusion module.
        #

        self.fusion = CrossAttentionFusionEx1NoTopK(
            embed_dim=embed_dim,
            num_heads=num_heads,
            dropout=dropout,
        )

        # ==================================================
        # Ordinal Regression Head
        # ==================================================

        self.ordinal_head = OrdinalRegressionHead(
            embed_dim=embed_dim,
            num_classes=num_classes,
            dropout=dropout,
        )

    def forward(
        self,
        x,
        return_attention=False,
    ):
        """
        Forward pass.

        Parameters
        ----------
        x : torch.Tensor
            Input image tensor.

            Shape:
                [B, 3, 224, 224]

        return_attention : bool
            If True, returns additional attention information.

        Returns
        -------
        logits : torch.Tensor

            Shape:
                [B, 3]

            Corresponding to:

                Grade > 0
                Grade > 1+
                Grade > 2+

        If return_attention=True, returns a dictionary containing:

            logits
            attention_weights
        """

        # ==================================================
        # Virchow2
        # ==================================================

        cls_token, register_tokens, patch_tokens = self.encoder(x)

        # patch_tokens:
        # [B, 256, 1280]

        # ==================================================
        # Cross Attention
        # ==================================================
        #
        # Unlike the main model, ALL patch tokens are used.
        #

        fused_feature, attention_weights = self.fusion(
            cls_token,
            patch_tokens,
        )

        # ==================================================
        # Ordinal Prediction
        # ==================================================

        logits = self.ordinal_head(
            fused_feature
        )

        # ==================================================
        # Optional Attention Output
        # ==================================================

        if return_attention:

            return {
                "logits": logits,
                "attention_weights": attention_weights,
            }

        return logits
